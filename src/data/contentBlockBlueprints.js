function cloneBlueprintBlock(block) {
  return {
    ...block,
    settings: JSON.parse(JSON.stringify(block?.settings || {})),
    editableFields: JSON.parse(JSON.stringify(Array.isArray(block?.editableFields) ? block.editableFields : [])),
  };
}

function templateScore(block) {
  const editableCount = Array.isArray(block?.editableFields) ? block.editableFields.length : 0;
  const settingsCount = block?.settings && typeof block.settings === 'object'
    ? Object.keys(block.settings).length
    : 0;
  const dynamicBoost = String(block?.mode || '').trim().toLowerCase() === 'dynamic' ? 3 : 0;
  return (editableCount * 10) + settingsCount + dynamicBoost;
}

export function getAllBlockTemplateBlueprints() {
  const byTemplateLookupId = new Map();
  const sources = [
    ...Object.values(contentBlockBlueprintsByPath || {}),
    genericPageBlockBlueprint(),
  ];

  sources.forEach((blocks) => {
    (Array.isArray(blocks) ? blocks : []).forEach((block) => {
      const templateLookupId = String(block?.id || '').trim();
      const templateId = resolveBlueprintSeedTemplateId(templateLookupId, block?.templateId);
      if (!templateLookupId || !templateId) {
        return;
      }
      const candidate = {
        ...cloneBlueprintBlock(block),
        templateLookupId,
        templateId,
      };
      const existing = byTemplateLookupId.get(templateLookupId);
      if (!existing || templateScore(candidate) > templateScore(existing)) {
        byTemplateLookupId.set(templateLookupId, candidate);
      }
    });
  });

  return Array.from(byTemplateLookupId.values()).sort((a, b) => {
    const nameCompare = String(a.name || '').localeCompare(String(b.name || ''));
    if (nameCompare !== 0) {
      return nameCompare;
    }
    return String(a.kind || '').localeCompare(String(b.kind || ''));
  });
}
