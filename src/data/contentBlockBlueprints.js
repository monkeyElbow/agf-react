export const PERSISTED_BLUEPRINT_BRIDGE_TEMPLATE_IDS = PERSISTED_COMPATIBILITY_BRIDGE_TEMPLATE_IDS;

export function resolveBlueprintSeedTemplateId(lookupId, explicitTemplateId = '') {
  const explicit = String(explicitTemplateId || '').trim();
  if (explicit) {
    return explicit;
  }
  const token = String(lookupId || '').trim();
  if (!token) {
    return '';
  }
  return CANONICAL_BLUEPRINT_SEED_TEMPLATE_IDS_BY_LOOKUP_ID[token] || token;
}

export function isPersistedBlueprintBridgeTemplateId(templateId) {
  const token = String(templateId || '').trim();
  return Boolean(token) && PERSISTED_BLUEPRINT_BRIDGE_TEMPLATE_IDS.includes(token);
}

function inferInternalPageRefFromHref(href) {
  const value = String(href || '').trim();
  return value.startsWith('/') ? value : '';
}

function seedBlueprintLinkFields({ hrefField, pageRefField, href = '', pageRef = inferInternalPageRefFromHref(href) }) {
  return {
    [hrefField]: href,
    [pageRefField]: pageRef,
  };
}

function seedBlueprintActionFields({
  labelField,
  hrefField,
  pageRefField,
  label = '',
  href = '',
  pageRef = inferInternalPageRefFromHref(href),
  styleField,
  style = 'blue',
  toneField,
  tone = 'atlantean',
  openInNewWindowField,
  openInNewWindow = false,
}) {
  return {
    [labelField]: label,
    ...seedBlueprintLinkFields({ hrefField, pageRefField, href, pageRef }),
    ...(styleField ? { [styleField]: style } : {}),
    ...(toneField ? { [toneField]: tone } : {}),
    ...(openInNewWindowField ? { [openInNewWindowField]: openInNewWindow } : {}),
  };
}

function seedBlueprintColumnButtonFields(columnNumber, options = {}) {
  return seedBlueprintActionFields({
    labelField: `col${columnNumber}ButtonLabel`,
    hrefField: `col${columnNumber}ButtonUrl`,
    pageRefField: `col${columnNumber}ButtonPageRef`,
    styleField: `col${columnNumber}ButtonStyle`,
    toneField: `col${columnNumber}ButtonTone`,
    ...options,
  });
}

